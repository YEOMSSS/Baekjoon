import sys

input = sys.stdin.readline


# [Summary] 저작권

# 멜로디의 개수를 곡의 개수로 나누면 평균값을 구할 수 있다.
# 평균값은 항상 올림을 해서 정수로 만든다.

# 곡의 개수와 올림된 평균값이 주어질 때,
# 멜로디의 개수의 최솟값을 구하시오.


def main() -> None:

    # [Ideas]

    # 멜로디개수/곡의개수 = 평균값
    # 멜로디개수 = 평균값*곡의개수

    # 그런데 평균값은 올림이 되어있다.
    # 그럼 평균값에서 1을 빼고 곡의개수와 곱한 다음 1을 더하면 된다.

    # 어! 그런데 딱 나눠떨어져서 올림이 없었다면 1을 빼면 안 된다.
    # 가 아니라, 무조건 올림이 있다고 가정하는 거잖아?
    # 그러면 곡이 하나일 때 빼고 전부 포함되겠네. 테스트케이스가 좋군.

    # 음, 평균값이 1이라면? 아, 이상하네 이거. 왜지?

    # 생각을 좀 다시 해보자. 올림이다.
    # 우리가 찾고 있는 건 멜로디 값의 최솟값이다.
    # 그러면 평균이 최대한 작았다고 생각해야 한다.
    # 지금 평균값이 24라면, 23.0000000.......000001이었다고 가정하자는거지.
    # 평균값 - 1에 한없이 가까운 게 원래 평균값이었다고 생각하고 곡 수를 곱한다.
    # 그럼 (곡 수) * (평균값 - 1)에 한없이 가까운 소수가 나오겠지.
    # 근데 멜로디의 개수는 소수가 될 수 없으니 그 값을 올려 +1을 하면 된다!~!!!!

    ##########

    A, I = map(int, input().split())

    print(A * (I - 1) + 1)

    ##########

    return


# [Review]

# 단순한 문제, 근데 왜 답인지 알기 위해선 꽤 생각이 필요할지도.
# 쉽지 않네, 재활이 많이 필요할 것 같다.


if __name__ == "__main__":
    main()
